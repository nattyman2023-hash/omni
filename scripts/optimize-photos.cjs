// Production-safe photograph optimisation. See optimize-photos-config.cjs.
const crypto = require('node:crypto');
const {
  ROOT, PHOTOS, OUT, WEBP_QUALITY, WEBP_EFFORT, JPEG_QUALITY, WIDTHS,
  slugFor, ALREADY_PUBLISHED, PUBLISHED_SLUGS, sharp, fs, path,
} = require('./optimize-photos-config.cjs');

const sources = fs.readdirSync(PHOTOS).filter((f) => /\.jpe?g$/i.test(f)).sort();

function sha256(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

async function emitOne(srcAbsolute, slug) {
  const image = sharp(srcAbsolute, { failOn: 'none' }).rotate(); // honour any EXIF
  const meta = await image.metadata();
  const produced = [];

  for (const width of WIDTHS) {
    if (width >= meta.width) continue; // never upscale — keeps detail honest
    const resized = sharp(srcAbsolute, { failOn: 'none' }).rotate().resize({ width, withoutEnlargement: true });
    const webpName = `${slug}-${width}.webp`;
    await resized.clone().webp({ quality: WEBP_QUALITY, effort: WEBP_EFFORT }).toFile(path.join(OUT, webpName));
    produced.push({ file: webpName, width });
  }

  // Full-size WebP (capped at the widest variant) plus a JPEG fallback.
  const base = sharp(srcAbsolute, { failOn: 'none' }).rotate().resize({ width: WIDTHS[WIDTHS.length - 1], withoutEnlargement: true });
  const webpName = `${slug}.webp`;
  const webp = await base.clone().webp({ quality: WEBP_QUALITY, effort: WEBP_EFFORT }).toFile(path.join(OUT, webpName));
  const jpegName = `${slug}.jpeg`;
  const jpeg = await base.clone().jpeg({ quality: JPEG_QUALITY, mozjpeg: true }).toFile(path.join(OUT, jpegName));

  const finalMeta = await sharp(path.join(OUT, webpName)).metadata();
  return {
    slug,
    webp: { file: webpName, bytes: webp.size, width: finalMeta.width, height: finalMeta.height },
    jpeg: { file: jpegName, bytes: jpeg.size },
    variants: produced,
    orientation: meta.width >= meta.height ? 'landscape' : 'portrait',
    sourceBytes: fs.statSync(srcAbsolute).size,
  };
}

/** Measure an asset that is already in production, without re-encoding it. */
async function measurePublished(slug) {
  const webpPath = path.join(OUT, `${slug}.webp`);
  const jpegPath = path.join(OUT, `${slug}.jpeg`);
  const webpMeta = await sharp(webpPath).metadata();
  const variants = WIDTHS.filter((width) => fs.existsSync(path.join(OUT, `${slug}-${width}.webp`)));
  return {
    slug,
    webp: { file: `${slug}.webp`, bytes: fs.statSync(webpPath).size, width: webpMeta.width, height: webpMeta.height },
    jpeg: { file: `${slug}.jpeg`, bytes: fs.existsSync(jpegPath) ? fs.statSync(jpegPath).size : 0 },
    variants: variants.map((width) => ({ file: `${slug}-${width}.webp`, width })),
    orientation: webpMeta.width >= webpMeta.height ? 'landscape' : 'portrait',
    sourceBytes: 0,
  };
}

async function main() {
  if (!fs.existsSync(OUT)) fs.mkdirSync(OUT, { recursive: true });

  const assets = [];
  const duplicates = [];
  let created = 0;
  let sourceTotal = 0;
  let webpTotal = 0;
  const seen = new Map();
  const seenHash = new Map();

  for (const filename of sources) {
    const srcAbsolute = path.join(PHOTOS, filename);
    const hash = sha256(srcAbsolute);

    // Byte-identical re-sends are recorded, not republished: emitting a second
    // copy of the same photograph would waste bandwidth and misrepresent the
    // library as larger than it is.
    if (seenHash.has(hash)) {
      duplicates.push({ filename, duplicateOf: seenHash.get(hash) });
      continue;
    }
    seenHash.set(hash, filename);

    const published = PUBLISHED_SLUGS[filename];
    const slug = published || slugFor(filename);
    // A repeated slug would silently overwrite another photograph's assets.
    if (seen.has(slug)) {
      throw new Error(`Slug collision "${slug}": "${seen.get(slug)}" and "${filename}"`);
    }
    seen.set(slug, filename);
    // Already-published assets are measured, not re-encoded, so the live site's
    // existing imagery is byte-for-byte preserved.
    const result = published
      ? await measurePublished(slug)
      : await emitOne(srcAbsolute, slug);
    if (!published) {
      created += 1;
      sourceTotal += fs.statSync(srcAbsolute).size;
      webpTotal += result.webp.bytes;
    }
    assets.push({ ...result, source: filename, alreadyPublished: Boolean(published) });
  }

  // Emit a typed asset index so every <img> can carry real width/height.
  assets.sort((a, b) => a.slug.localeCompare(b.slug));
  const lines = [];
  lines.push('// GENERATED by scripts/optimize-photos.cjs — do not edit by hand.');
  lines.push('// Width and height are measured from the published WebP, so every consumer can');
  lines.push('// set explicit dimensions and avoid cumulative layout shift.');
  lines.push('export type PhotoOrientation = "landscape" | "portrait";');
  lines.push('');
  lines.push('export interface PhotoAsset {');
  lines.push('  slug: string;');
  lines.push('  /** Path served from /images. */');
  lines.push('  webp: string;');
  lines.push('  jpeg: string;');
  lines.push('  width: number;');
  lines.push('  height: number;');
  lines.push('  orientation: PhotoOrientation;');
  lines.push('  /** Smaller responsive variants, widest first. */');
  lines.push('  variants: number[];');
  lines.push('  /** Original supplied filename, kept for owner traceability. */');
  lines.push('  source: string;');
  lines.push('}');
  lines.push('');
  lines.push('export const PHOTO_ASSETS: PhotoAsset[] = [');
  for (const a of assets) {
    const variants = a.variants.map((v) => v.width).sort((x, y) => y - x).join(', ');
    lines.push('  {');
    lines.push(`    slug: ${JSON.stringify(a.slug)},`);
    lines.push(`    webp: ${JSON.stringify(`/images/${a.webp.file}`)},`);
    lines.push(`    jpeg: ${JSON.stringify(`/images/${a.jpeg.file}`)},`);
    lines.push(`    width: ${a.webp.width},`);
    lines.push(`    height: ${a.webp.height},`);
    lines.push(`    orientation: ${JSON.stringify(a.orientation)},`);
    lines.push(`    variants: [${variants}],`);
    lines.push(`    source: ${JSON.stringify(a.source)},`);
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  lines.push('export const PHOTO_ASSET_BY_SLUG: Record<string, PhotoAsset> = Object.fromEntries(');
  lines.push('  PHOTO_ASSETS.map((asset) => [asset.slug, asset]),');
  lines.push(');');
  lines.push('');
  // Helpers are generated alongside the data so consumers cannot drift from the
  // real filenames on disk. Variant files are always `${slug}-${width}.webp`.
  lines.push('/** Path of a responsive variant, e.g. `/images/garden-beds-960.webp`. */');
  lines.push('export function photoVariantPath(asset: PhotoAsset, width: number): string {');
  lines.push('  return `/images/${asset.slug}-${width}.webp`;');
  lines.push('}');
  lines.push('');
  lines.push('/**');
  lines.push(' * WebP `srcSet`, narrowest first, always ending on the full-size frame so the');
  lines.push(' * browser never has to interpolate a rung that was not actually generated.');
  lines.push(' */');
  lines.push('export function photoWebpSrcSet(asset: PhotoAsset): string {');
  lines.push('  const rungs = [...asset.variants]');
  lines.push('    .sort((a, b) => a - b)');
  lines.push('    .filter((width) => width < asset.width)');
  lines.push('    .map((width) => `${photoVariantPath(asset, width)} ${width}w`);');
  lines.push('  rungs.push(`${asset.webp} ${asset.width}w`);');
  lines.push('  return rungs.join(", ");');
  lines.push('}');
  lines.push('');
  lines.push('/**');
  lines.push(' * JPEG fallback `srcSet`. Responsive variants are WebP only, so this is a');
  lines.push(' * single rung; it exists for browsers with no WebP support.');
  lines.push(' */');
  lines.push('export function photoJpegSrcSet(asset: PhotoAsset): string {');
  lines.push('  return `${asset.jpeg} ${asset.width}w`;');
  lines.push('}');
  lines.push('');
  lines.push('/** CSS `aspect-ratio` value, so containers reserve exact space and never shift. */');
  lines.push('export function photoAspectRatio(asset: PhotoAsset): string {');
  lines.push('  return `${asset.width} / ${asset.height}`;');
  lines.push('}');
  lines.push('');
  lines.push('/** Looks an asset up by slug and fails loudly instead of rendering a broken image. */');
  lines.push('export function photo(slug: string): PhotoAsset {');
  lines.push('  const asset = PHOTO_ASSET_BY_SLUG[slug];');
  lines.push('  if (!asset) throw new Error(`Unknown photo asset slug: ${slug}`);');
  lines.push('  return asset;');
  lines.push('}');
  lines.push('');
  lines.push('/** Portrait pool for the neutral cards, rails and grids in docs/PHOTO_USAGE_PLAN.md. */');
  lines.push('export const PORTRAIT_PHOTO_ASSETS = PHOTO_ASSETS.filter((asset) => asset.orientation === "portrait");');
  lines.push('');
  lines.push('/** Landscape pool — the only frames safe for wide slots. */');
  lines.push('export const LANDSCAPE_PHOTO_ASSETS = PHOTO_ASSETS.filter((asset) => asset.orientation === "landscape");');
  lines.push('');

  const tsPath = path.join(ROOT, 'client', 'src', 'data', 'photoAssets.ts');
  fs.writeFileSync(tsPath, lines.join('\n'), 'utf8');

  // Raw index for the docs pipeline.
  fs.writeFileSync(
    path.join(ROOT, 'docs', '_photo_assets.json'),
    JSON.stringify({ assets, duplicates }, null, 2),
    'utf8'
  );

  const uniqueCount = assets.length;
  const publishedCount = assets.filter((a) => a.alreadyPublished).length;
  console.log(`scanned ${sources.length} files -> ${uniqueCount} unique photographs`);
  console.log(`  already published: ${publishedCount}`);
  console.log(`  newly optimised:   ${created}`);
  console.log(`  duplicates skipped: ${duplicates.length}`);
  for (const dup of duplicates) {
    console.log(`    "${dup.filename}" is byte-identical to "${dup.duplicateOf}"`);
  }
  const saved = sourceTotal - webpTotal;
  console.log(`new base WebP ${(webpTotal / 1024).toFixed(0)} KB vs originals ${(sourceTotal / 1024).toFixed(0)} KB (${(100 * saved / sourceTotal).toFixed(1)}% smaller)`);
  console.log(`wrote ${tsPath}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
